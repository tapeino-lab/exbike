const ROWS: Record<string, boolean[][]> = Object.fromEntries(
  Object.entries(GLYPHS).map(([ch, g]) => [ch, g.split(' ').map((r) => [...r].map((c) => c === '1'))]),
);

export const CHAR_W = 6;
export const CHAR_H = 7;

export function textWidth(text: string, scale = 1): number {
  return Math.max(0, text.length * CHAR_W - 1) * scale;
}

/** Draws text with its top-left corner at (x, y). */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, scale = 1): void {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of text.toUpperCase()) {
    const rows = ROWS[ch] ?? ROWS[' '];
    for (let r = 0; r < CHAR_H; r++) {
      for (let c = 0; c < 5; c++) {
        if (rows[r][c]) ctx.fillRect(cx + c * scale, cy + r * scale, scale, scale);
      }
    }
    cx += CHAR_W * scale;
  }
}

/** Text centred on x, with a 1px drop shadow. */
export function drawTextCentered(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  shadow = '#000',
): void {
  const left = x - textWidth(text, scale) / 2;
  drawText(ctx, text, left + scale, y + scale, shadow, scale);
  drawText(ctx, text, left, y, color, scale);
}
